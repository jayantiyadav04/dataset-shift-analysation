"""Record or verify installed pins. This is an environment snapshot, not a solver."""

import argparse
import platform
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def installed_pins() -> list[str]:
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--all", "--exclude-editable"],
        capture_output=True,
        text=True,
        check=True,
    )
    pins = [line for line in result.stdout.splitlines() if line and not line.startswith("#")]
    if not pins or any(
        re.fullmatch(r"[A-Za-z0-9_.-]+==[A-Za-z0-9_.+!-]+", pin) is None for pin in pins
    ):
        raise ValueError("All noneditable dependencies must have exact registry version pins")
    if any(pin.lower().startswith("domain-shift-workbench==") for pin in pins):
        raise ValueError("Install this project in editable mode before capturing dependencies")
    return sorted(pins, key=str.casefold)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument(
        "--write", action="store_true", help="Create a new lock, refusing overwrite"
    )
    action.add_argument(
        "--check", action="store_true", help="Compare all installed dependency pins"
    )
    args = parser.parse_args()
    pins = installed_pins()
    path = ROOT / "requirements-lock.txt"
    if args.write:
        header = (
            "# Actual installed environment snapshot; no editable paths.\n"
            f"# CPython {platform.python_version()}; {platform.system()} {platform.machine()}.\n"
            "# Install these pins before the local package with --no-deps --no-build-isolation.\n"
            "# Generated by: python tools/lock_environment.py --write\n"
        )
        with path.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(header + "\n".join(pins) + "\n")
        print(f"Recorded {len(pins)} actual dependency pins in {path.name}")
    else:
        expected = [
            line
            for line in path.read_text(encoding="utf-8").splitlines()
            if line and not line.startswith("#")
        ]
        if pins != expected:
            print(
                "FAIL: installed dependency versions differ from requirements-lock.txt",
                file=sys.stderr,
            )
            return 1
        print(f"PASS: all {len(pins)} installed dependency pins match requirements-lock.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
